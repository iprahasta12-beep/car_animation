# Bake all cars into preview/data.js so preview/index.html opens offline (double-click, file://).
# usage: python3 bake.py <car-animation root>
# Each car = cars/<id>/ with car.json + car.atlas + atlas page png(s) [+ meta.json {label, desc, order}] [+ thumb.png]
import json, base64, os, sys, re
root = sys.argv[1]
def url(p): return "data:image/png;base64," + base64.b64encode(open(p, "rb").read()).decode()
def pages(atlas): return [l.strip() for l in atlas.splitlines() if re.search(r"\.(png|jpe?g|webp)$", l.strip(), re.I)]
cars = []
cdir = os.path.join(root, "cars")
for cid in sorted(os.listdir(cdir)):
    d = os.path.join(cdir, cid)
    if not os.path.isfile(os.path.join(d, "car.json")): continue
    meta = json.load(open(os.path.join(d, "meta.json"))) if os.path.isfile(os.path.join(d, "meta.json")) else {}
    at = open(os.path.join(d, "car.atlas")).read()
    cars.append({"id": cid, "label": meta.get("label", cid), "desc": meta.get("desc", ""), "order": meta.get("order", 99),
                 "skeleton": open(os.path.join(d, "car.json")).read(), "atlas": at,
                 "images": {n: url(os.path.join(d, n)) for n in pages(at)},
                 "thumb": url(os.path.join(d, "thumb.png")) if os.path.isfile(os.path.join(d, "thumb.png")) else ""})
cars.sort(key=lambda c: (c["order"], c["id"]))
sd = os.path.join(root, "scene"); pl = json.load(open(os.path.join(sd, "placements.json")))
scene = {"placements": pl, "background": url(os.path.join(sd, pl["background"]))}
out = os.path.join(root, "preview", "data.js")
open(out, "w").write("// AUTO-GENERATED by tools/bake.py\nwindow.CAR_DATA = " + json.dumps({"cars": cars, "scene": scene}) + ";\n")
print(len(cars), "cars,", os.path.getsize(out) // 1024, "KB")
